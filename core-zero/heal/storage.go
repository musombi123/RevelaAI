// Package heal implements guarded recovery proposals.
//
// This file provides local persistence helpers. Persisting or loading a
// proposal does not approve it, execute it, or authorize a filesystem change.
package heal

import (
	"bytes"
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"usect-zero.local/core-zero/internal/kernel"
)

const maxHealJSONBytes int64 = 1 << 20 // 1 MiB

// newID generates a cryptographically random 96-bit lowercase hexadecimal ID.
func newID() (string, error) {
	raw := make([]byte, 12)

	if _, err := rand.Read(raw); err != nil {
		return "", fmt.Errorf("generate recovery proposal ID: %w", err)
	}

	return hex.EncodeToString(raw), nil
}

// validProposalID restricts proposal identifiers to IDs generated by newID.
// IDs are used as filename components, never as arbitrary relative paths.
func validProposalID(id string) bool {
	if len(id) != 24 || id != strings.ToLower(id) {
		return false
	}

	raw, err := hex.DecodeString(id)
	return err == nil && len(raw) == 12
}

// gitOutput delegates to the existing guarded Git helper.
func gitOutput(root string, args ...string) ([]byte, error) {
	return runGit(root, args...)
}

// kWriteProposal persists one proposal in the managed state directory.
//
// This helper does not mark the proposal approved and does not execute it.
func kWriteProposal(k *kernel.Kernel, proposal Proposal) error {
	if k == nil {
		return errors.New("recovery kernel is not initialized")
	}

	if strings.TrimSpace(k.CoreRoot) == "" {
		return errors.New("recovery state root is not configured")
	}

	if !validProposalID(proposal.ID) {
		return errors.New("invalid recovery proposal ID")
	}

	relative := filepath.Join(
		"state",
		"proposals",
		"heal-"+proposal.ID+".json",
	)

	return writeJSON(k.CoreRoot, relative, proposal)
}

// kReadProposal loads a proposal by its validated identifier.
//
// It rejects invalid IDs and unsafe persistence paths before reading data.
func kReadProposal(k *kernel.Kernel, id string, proposal *Proposal) error {
	if k == nil || strings.TrimSpace(k.CoreRoot) == "" {
		return errors.New("recovery state root is not configured")
	}

	if proposal == nil {
		return errors.New("recovery proposal destination is nil")
	}

	if !validProposalID(id) {
		return os.ErrNotExist
	}

	relative := filepath.Join(
		"state",
		"proposals",
		"heal-"+id+".json",
	)

	if err := readJSON(k.CoreRoot, relative, proposal); err != nil {
		return fmt.Errorf("read recovery proposal: %w", err)
	}

	if proposal.ID != id {
		return errors.New("stored proposal ID does not match requested ID")
	}

	return nil
}

// cleanHealRelative validates a path relative to the configured state root.
// It rejects absolute paths, traversal components, NUL bytes, backslashes,
// volume names and paths that normalize outside the managed directory.
func cleanHealRelative(relative string) (string, error) {
	if relative == "" ||
		strings.TrimSpace(relative) == "" ||
		strings.ContainsRune(relative, '\x00') ||
		strings.Contains(relative, "\\") ||
		filepath.IsAbs(relative) {
		return "", errors.New("state path must be a non-empty relative path")
	}

	relative = filepath.FromSlash(relative)

	if filepath.VolumeName(relative) != "" {
		return "", errors.New("state path must not contain a volume name")
	}

	for _, part := range strings.Split(relative, string(filepath.Separator)) {
		if part == ".." {
			return "", errors.New("state path contains a traversal component")
		}
	}

	clean := filepath.Clean(relative)

	if clean == "." ||
		clean == ".." ||
		filepath.IsAbs(clean) ||
		strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", errors.New("state path escapes its configured root")
	}

	return clean, nil
}

// healRoot resolves the configured data root and refuses a symlink as its
// final path component. Parent components are resolved to their canonical
// location before managed relative paths are evaluated.
func healRoot(root string, create bool) (string, error) {
	if strings.TrimSpace(root) == "" {
		return "", errors.New("state root is not configured")
	}

	absolute, err := filepath.Abs(root)
	if err != nil {
		return "", fmt.Errorf("resolve state root: %w", err)
	}
	absolute = filepath.Clean(absolute)

	info, err := os.Lstat(absolute)
	if errors.Is(err, os.ErrNotExist) && create {
		if err := os.MkdirAll(absolute, 0700); err != nil {
			return "", fmt.Errorf("create state root: %w", err)
		}
		info, err = os.Lstat(absolute)
	}

	if err != nil {
		return "", fmt.Errorf("inspect state root: %w", err)
	}

	if info.Mode()&os.ModeSymlink != 0 {
		return "", errors.New("state root must not be a symbolic link")
	}

	if !info.IsDir() {
		return "", errors.New("state root is not a directory")
	}

	canonical, err := filepath.EvalSymlinks(absolute)
	if err != nil {
		return "", fmt.Errorf("resolve state root symlinks: %w", err)
	}

	canonical = filepath.Clean(canonical)

	return canonical, nil
}

// healDirectory validates the directory components beneath root.
//
// When create is true, missing components are created individually with
// restricted permissions. Existing symlinked components are rejected.
func healDirectory(root, relative string, create bool) (string, error) {
	clean, err := cleanHealRelative(relative)
	if err != nil {
		return "", err
	}

	canonicalRoot, err := healRoot(root, create)
	if err != nil {
		return "", err
	}

	current := canonicalRoot

	for _, part := range strings.Split(clean, string(filepath.Separator)) {
		if part == "" || part == "." || part == ".." {
			return "", errors.New("invalid managed directory component")
		}

		current = filepath.Join(current, part)

		info, err := os.Lstat(current)

		if errors.Is(err, os.ErrNotExist) && create {
			if err := os.Mkdir(current, 0700); err != nil &&
				!errors.Is(err, os.ErrExist) {
				return "", fmt.Errorf("create managed directory: %w", err)
			}

			info, err = os.Lstat(current)
		}

		if err != nil {
			return "", fmt.Errorf("inspect managed directory: %w", err)
		}

		if info.Mode()&os.ModeSymlink != 0 {
			return "", errors.New("refusing symlinked managed directory")
		}

		if !info.IsDir() {
			return "", errors.New("managed path is not a directory")
		}
	}

	return current, nil
}

// healManagedFile returns a checked file path beneath root.
//
// Its parent directory must exist when createParent is false. The final
// file may be absent, but an existing final component must be a regular file
// and must not be a symbolic link.
func healManagedFile(root, relative string, createParent bool) (string, error) {
	clean, err := cleanHealRelative(relative)
	if err != nil {
		return "", err
	}

	canonicalRoot, err := healRoot(root, createParent)
	if err != nil {
		return "", err
	}

	parentRelative := filepath.Dir(clean)
	parent := canonicalRoot

	if parentRelative != "." {
		parent, err = healDirectory(canonicalRoot, parentRelative, createParent)
		if err != nil {
			return "", err
		}
	}

	destination := filepath.Join(parent, filepath.Base(clean))

	// Confirm the final path is still within the canonical root.
	rel, err := filepath.Rel(canonicalRoot, destination)
	if err != nil ||
		rel == ".." ||
		filepath.IsAbs(rel) ||
		strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", errors.New("state file escapes its configured root")
	}

	info, err := os.Lstat(destination)

	if err == nil {
		if info.Mode()&os.ModeSymlink != 0 {
			return "", errors.New("refusing a symlinked state file")
		}

		if !info.Mode().IsRegular() {
			return "", errors.New("state file is not a regular file")
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", fmt.Errorf("inspect managed state file: %w", err)
	}

	return destination, nil
}

// writeJSON atomically persists a JSON document beneath root.
//
// The write is performed through a unique temporary file in the destination
// directory. File permissions are restricted, contents are synced before
// rename, and the destination is rechecked before replacement.
func writeJSON(root, relative string, value any) error {
	encoded, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		return fmt.Errorf("encode recovery state: %w", err)
	}

	encoded = append(encoded, '\n')

	if int64(len(encoded)) > maxHealJSONBytes {
		return errors.New("recovery state exceeds the maximum allowed file size")
	}

	destination, err := healManagedFile(root, relative, true)
	if err != nil {
		return err
	}

	parent := filepath.Dir(destination)

	// The temporary file lives on the same filesystem as the target so the
	// rename is atomic on filesystems that provide normal rename semantics.
	temp, err := os.CreateTemp(parent, ".usect-zero-heal-*.tmp")
	if err != nil {
		return fmt.Errorf("create temporary recovery state: %w", err)
	}

	tempPath := temp.Name()
	defer os.Remove(tempPath)

	if err := temp.Chmod(0600); err != nil {
		_ = temp.Close()
		return fmt.Errorf("secure temporary recovery state: %w", err)
	}

	n, err := temp.Write(encoded)
	if err != nil {
		_ = temp.Close()
		return fmt.Errorf("write temporary recovery state: %w", err)
	}

	if n != len(encoded) {
		_ = temp.Close()
		return io.ErrShortWrite
	}

	if err := temp.Sync(); err != nil {
		_ = temp.Close()
		return fmt.Errorf("sync temporary recovery state: %w", err)
	}

	if err := temp.Close(); err != nil {
		return fmt.Errorf("close temporary recovery state: %w", err)
	}

	// Recheck the destination immediately before replacement.
	rechecked, err := healManagedFile(root, relative, false)
	if err != nil {
		return fmt.Errorf("revalidate recovery destination: %w", err)
	}

	if rechecked != destination {
		return errors.New("recovery destination changed during persistence")
	}

	if err := os.Rename(tempPath, destination); err != nil {
		return fmt.Errorf("commit recovery state: %w", err)
	}

	syncHealDirectoryBestEffort(parent)

	return nil
}

// readJSON reads one bounded JSON value beneath root. It rejects symlinks,
// special files, oversized state and trailing JSON values.
func readJSON(root, relative string, destination any) error {
	if destination == nil {
		return errors.New("JSON destination must not be nil")
	}

	source, err := healManagedFile(root, relative, false)
	if err != nil {
		return err
	}

	file, err := os.Open(source)
	if err != nil {
		return fmt.Errorf("open recovery state: %w", err)
	}

	openedInfo, statErr := file.Stat()
	pathInfo, pathErr := os.Lstat(source)

	if statErr != nil ||
		pathErr != nil ||
		pathInfo.Mode()&os.ModeSymlink != 0 ||
		!openedInfo.Mode().IsRegular() ||
		!os.SameFile(openedInfo, pathInfo) {
		_ = file.Close()
		return errors.New("recovery state changed or is not a safe regular file")
	}

	if openedInfo.Size() > maxHealJSONBytes {
		_ = file.Close()
		return errors.New("recovery state exceeds the maximum allowed file size")
	}

	raw, readErr := io.ReadAll(io.LimitReader(file, maxHealJSONBytes+1))
	closeErr := file.Close()

	if readErr != nil {
		return fmt.Errorf("read recovery state: %w", readErr)
	}

	if closeErr != nil {
		return fmt.Errorf("close recovery state: %w", closeErr)
	}

	if int64(len(raw)) > maxHealJSONBytes {
		return errors.New("recovery state exceeds the maximum allowed file size")
	}

	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()

	if err := decoder.Decode(destination); err != nil {
		return fmt.Errorf("decode recovery state: %w", err)
	}

	var trailing any
	if err := decoder.Decode(&trailing); err != io.EOF {
		if err == nil {
			return errors.New("recovery state must contain exactly one JSON value")
		}

		return fmt.Errorf("invalid trailing recovery state data: %w", err)
	}

	return nil
}

// syncHealDirectoryBestEffort requests persistence of directory metadata
// where the operating system and filesystem support it.
func syncHealDirectoryBestEffort(directory string) {
	file, err := os.Open(directory)
	if err != nil {
		return
	}
	defer file.Close()

	_ = file.Sync()
}

"""Deterministic, model-free proposal builder for RevelaAI's Meta-Engineer.

The builder creates target-aware, reviewable scaffolds. It never imports candidate
code, writes it into the production import path, or deploys it automatically.
"""
from __future__ import annotations

import ast
import json
import re
from datetime import datetime, timezone
from typing import Any

TARGETS = {"backend", "frontend", "database", "fullstack"}


def _slug(spec: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", spec.lower()).strip("_")[:48] or "proposed_feature"


def _component_name(slug: str) -> str:
    name = "".join(part[:1].upper() + part[1:] for part in slug.split("_") if part)
    if not name or name[0].isdigit():
        name = "Feature" + name
    return name + "Proposal"


def _normalize_request(spec: str, target: str | None) -> tuple[str, str]:
    clean = " ".join(str(spec or "").split())
    # Compatibility with the previous route's wrapper format.
    wrapped = re.match(
        r"^Target surface:\s*(backend|frontend|database|fullstack)\.\s*Feature specification:\s*(.*)$",
        clean,
        re.IGNORECASE,
    )
    if wrapped:
        if target is None:
            target = wrapped.group(1)
        clean = wrapped.group(2).strip()

    selected = str(target or "backend").strip().lower()
    if selected not in TARGETS:
        raise ValueError("target must be one of: backend, frontend, database, fullstack")
    if not clean or len(clean) > 1000:
        raise ValueError("spec must be 1–1000 characters")
    if any(term in clean.lower() for term in ("delete core", "edit jwt", "disable auth", "exfiltrate")):
        raise ValueError("spec requests a protected or unsafe operation")
    return clean, selected


def _backend_artifact(spec: str, slug: str, stamp: str) -> dict[str, str]:
    match = re.search(r"\b(GET|POST|PUT|PATCH|DELETE)\s+(/[A-Za-z0-9_/{}/.-]+)", spec, re.IGNORECASE)
    method = match.group(1).lower() if match else "get"
    endpoint = match.group(2) if match else "/api/proposals/" + slug
    if method == "delete":
        raise ValueError("destructive route proposals require separate human review")
    if ".." in endpoint or "//" in endpoint or not endpoint.startswith("/"):
        raise ValueError("unsafe route path")
    if endpoint.count("{") != endpoint.count("}"):
        raise ValueError("route path has an unbalanced parameter placeholder")

    code = (
        '"""Review-gated Flask route scaffold generated by Meta-Engineer."""\n'
        "from __future__ import annotations\n\n"
        "from flask import Blueprint, jsonify, request\n\n"
        "# AUTO-GENERATED " + stamp + " — proposal only; not registered in the live application.\n"
        "router = Blueprint(" + repr(slug) + ", __name__)\n\n"
        "@router." + method + "(" + repr(endpoint) + ")\n"
        "def proposed_feature():\n"
        '    """Safe scaffold. Replace the proposal payload with reviewed feature logic."""\n'
        '    if request.method in {"POST", "PUT", "PATCH"}:\n'
        "        payload = request.get_json(silent=True)\n"
        "        if payload is not None and not isinstance(payload, dict):\n"
        '            return jsonify({"status": "error", "code": "invalid_payload"}), 400\n'
        "    return jsonify({\n"
        '        "status": "proposed",\n'
        '        "proposal_only": True,\n'
        '        "feature": ' + repr(slug) + ",\n"
        '        "specification": ' + repr(spec) + ",\n"
        '        "requires_approval": True,\n'
        "    }), 200\n"
    )
    ast.parse(code)
    return {
        "path": "backend-proposals/" + slug + ".py",
        "content": code,
        "language": "python",
        "role": "backend_route",
    }


def _frontend_artifact(spec: str, slug: str, stamp: str) -> dict[str, str]:
    component = _component_name(slug)
    # JSON string encoding prevents the specification from becoming executable JSX.
    specification_literal = json.dumps(spec, ensure_ascii=True)
    code = (
        "// AUTO-GENERATED " + stamp + " — review-only React scaffold.\n"
        "import React, { useState } from \"react\";\n\n"
        "const FEATURE_SPEC = " + specification_literal + ";\n\n"
        "export default function " + component + "() {\n"
        "  const [showSpecification, setShowSpecification] = useState(true);\n"
        "  return (\n"
        "    <section aria-labelledby=\"feature-proposal-title\" className=\"rounded-xl border p-4\">\n"
        "      <div className=\"flex items-center justify-between gap-3\">\n"
        "        <h2 id=\"feature-proposal-title\" className=\"font-semibold\">Feature proposal</h2>\n"
        "        <span className=\"rounded-full border px-2 py-1 text-xs\">Proposed</span>\n"
        "      </div>\n"
        "      <p className=\"mt-2 text-sm\">This generated scaffold is not yet integrated into the product.</p>\n"
        "      <button type=\"button\" className=\"mt-3 rounded-lg border px-3 py-2 text-sm\"\n"
        "        onClick={() => setShowSpecification((shown) => !shown)}>\n"
        "        {showSpecification ? \"Hide specification\" : \"Show specification\"}\n"
        "      </button>\n"
        "      {showSpecification ? <pre className=\"mt-3 whitespace-pre-wrap text-xs\">{FEATURE_SPEC}</pre> : null}\n"
        "    </section>\n"
        "  );\n"
        "}\n"
    )
    if "export default function " not in code or "FEATURE_SPEC" not in code:
        raise ValueError("frontend scaffold failed its structural checks")
    return {
        "path": "frontend-proposals/" + slug + ".jsx",
        "content": code,
        "language": "jsx",
        "role": "frontend_component",
    }


def _database_artifact(spec: str, slug: str, stamp: str) -> dict[str, str]:
    code = (
        '"""Mongo-compatible document contract scaffold; no database writes occur here."""\n'
        "from __future__ import annotations\n\n"
        "from dataclasses import dataclass, field\n"
        "from datetime import datetime, timezone\n"
        "from typing import Any\n\n"
        "# AUTO-GENERATED " + stamp + " — proposal only; review before integration.\n"
        "@dataclass(frozen=True)\n"
        "class FeatureProposalRecord:\n"
        "    title: str\n"
        "    specification: str = " + repr(spec) + "\n"
        '    status: str = "proposed"\n'
        "    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())\n\n"
        "    def to_document(self) -> dict[str, Any]:\n"
        "        title = self.title.strip()\n"
        "        specification = self.specification.strip()\n"
        "        if not title or not specification:\n"
        '            raise ValueError("title and specification are required")\n'
        "        return {\n"
        '            "title": title,\n'
        '            "specification": specification,\n'
        '            "status": self.status,\n'
        '            "created_at": self.created_at,\n'
        "        }\n\n"
        "    @classmethod\n"
        "    def from_document(cls, document: dict[str, Any]) -> FeatureProposalRecord:\n"
        "        if not isinstance(document, dict):\n"
        '            raise TypeError("document must be a mapping")\n'
        "        return cls(\n"
        '            title=str(document.get("title") or ""),\n'
        '            specification=str(document.get("specification") or ""),\n'
        '            status=str(document.get("status") or "proposed"),\n'
        '            created_at=str(document.get("created_at") or datetime.now(timezone.utc).isoformat()),\n'
        "        )\n"
    )
    ast.parse(code)
    return {
        "path": "database-proposals/" + slug + "_model.py",
        "content": code,
        "language": "python",
        "role": "document_schema",
    }


def generate_feature(spec: str, target: str | None = None) -> dict[str, Any]:
    """Build one target-specific scaffold or a three-file full-stack bundle.

    This is deliberately deterministic and model-free. It produces reviewable
    scaffolding, not arbitrary finished business logic.
    """
    clean, selected = _normalize_request(spec, target)
    stamp = datetime.now(timezone.utc).isoformat()
    slug = _slug(clean)
    files: list[dict[str, str]] = []

    if selected in {"backend", "fullstack"}:
        files.append(_backend_artifact(clean, slug, stamp))
    if selected in {"database", "fullstack"}:
        files.append(_database_artifact(clean, slug, stamp))
    if selected in {"frontend", "fullstack"}:
        files.append(_frontend_artifact(clean, slug, stamp))

    if selected == "backend":
        kind = "python_flask_route_proposal"
    elif selected == "frontend":
        kind = "react_component_proposal"
    elif selected == "database":
        kind = "python_document_schema_proposal"
    else:
        kind = "fullstack_proposal_bundle"

    primary = files[0]
    syntax_valid = True
    for artifact in files:
        if artifact["language"] == "python":
            try:
                ast.parse(artifact["content"], filename=artifact["path"])
            except SyntaxError:
                syntax_valid = False
        elif artifact["language"] == "jsx":
            syntax_valid = syntax_valid and "export default function " in artifact["content"]

    return {
        "feature": slug,
        "kind": kind,
        "target": selected,
        "code_path": primary["path"],
        "code": primary["content"],
        "files": files,
        "spec": clean,
        "timestamp": stamp,
        "syntax_valid": syntax_valid,
        "runtime_integration": "disabled_until_human_approval",
        "auto_deploy": False,
    }

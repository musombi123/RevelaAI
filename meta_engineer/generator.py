"""Deterministic proposal generator. Candidate code is never auto-imported."""
from __future__ import annotations
import ast, re
from datetime import datetime, timezone

def _slug(spec: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", spec.lower()).strip("_")[:48] or "proposed_feature"

def generate_feature(spec: str) -> dict:
    clean = " ".join(str(spec or "").split())
    if not clean or len(clean) > 1000:
        raise ValueError("spec must be 1–1000 characters")
    if any(x in clean.lower() for x in ("delete core", "edit jwt", "disable auth", "exfiltrate")):
        raise ValueError("spec requests a protected or unsafe operation")
    slug = _slug(clean)
    stamp = datetime.now(timezone.utc).isoformat()
    if any(x in clean.lower() for x in ("typescript", "react component", "frontend component", ".tsx")):
        title = repr(clean)
        code = (
            "/** AUTO-GENERATED by Meta-Engineer " + stamp + " - spec: " + clean.replace("*/", "* /") + " */\n"
            "export type ProposalStatus = \"proposed\";\n"
            "export interface FeatureProposal { title: string; status: ProposalStatus }\n"
            "export const featureProposal: FeatureProposal = { title: " + title + ", status: \"proposed\" };\n"
        )
        kind, path = "typescript_react_proposal", "frontend-proposals/" + slug + ".tsx"
    else:
        match = re.search(r"\b(GET|POST|PUT|PATCH|DELETE)\s+(/[A-Za-z0-9_/{}/.-]+)", clean, re.I)
        method = match.group(1).lower() if match else "get"
        endpoint = match.group(2) if match else "/api/proposals/" + slug
        if ".." in endpoint or "//" in endpoint:
            raise ValueError("unsafe route path")
        if method == "delete":
            raise ValueError("destructive route proposals require separate human review")
        response = {"status": "ok", "module": "meta-engineer", "proposal_only": True} if endpoint == "/api/health/meta" else {"status": "proposed", "feature": slug, "requires_approval": True}
        # repr() produces a Python literal, not executable spec text.
        code = (
            '"""Proposal artifact; adapt to the existing Flask app before integration."""\n'
            "# AUTO-GENERATED by Meta-Engineer " + stamp + " - spec: " + clean + "\n"
            "from flask import Blueprint, jsonify\n"
            'router = Blueprint("' + slug + '", __name__)\n'
            '@router.' + method + '("' + endpoint + '")\n'
            "def proposed_feature():\n"
            '    """Non-mutating placeholder response for human review."""\n'
            "    try:\n"
            "        return jsonify(" + repr(response) + ")\n"
            "    except Exception:\n"
            '        return jsonify({"status": "error", "message": "Feature proposal failed"}), 500\n'
        )
        ast.parse(code)
        kind, path = "python_flask_route_proposal", "proposals/" + slug + ".py"
    return {"feature": slug, "kind": kind, "code_path": path, "code": code,
            "spec": clean, "timestamp": stamp, "syntax_valid": True,
            "runtime_integration": "disabled_until_human_approval"}

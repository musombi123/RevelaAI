const (
	maxGeneratedActionBytes = 2000
	maxGeneratedInputCount  = 100
	maxGeneratedInputKeyLen = 100
	maxGeneratedInputValLen = 4000
	maxGeneratedItems       = 128
	maxGeneratedTextBytes   = 2000
)

// generatedCode builds a deterministic, non-executing tool proposal.
// Generated source contains no model-provided executable code.
func generatedCode(spec ToolSpec) string {
	route := generatedToolRoute(spec.Name)
	pkg := generatedGoPackageName(route)
	title := generatedSingleLine(spec.Title, 160)
	if title == "" {
		title = route
	}

	category := generatedSingleLine(spec.Category, 120)
	purpose := generatedSingleLine(spec.Purpose, 1000)

	return fmt.Sprintf(`// Code generated by Revela Genesis %s.
// Proposal: %s
// Review before activation. DO NOT EDIT generated code without review.
package %s

import (
	"errors"
	"strings"
	"time"
	"unicode"
	"unicode/utf8"
)

const (
	ToolName = %q
	ToolCategory = %q
	ToolPurpose = %q

	maxActionBytes = %d
	maxInputCount = %d
	maxInputKeyBytes = %d
	maxInputValueBytes = %d
)

var Capabilities = []string{%s}
var Safeguards = []string{%s}

type Request struct {
	Action string
	Inputs map[string]string
	Consent bool
}

type Result struct {
	Status string
	Tool string
	Summary string
	CreatedAt time.Time
	Evidence []string
}

type Tool struct{}

func validToolText(value string, maxBytes int, allowWhitespace bool) bool {
	if !utf8.ValidString(value) || len(value) > maxBytes {
		return false
	}
	for _, r := range value {
		if unicode.IsControl(r) {
			if !allowWhitespace || !unicode.IsSpace(r) {
				return false
			}
		}
	}
	return true
}

// Run validates inputs and emits a proposal only.
// It performs no I/O, device actuation, or network requests.
func (Tool) Run(req Request) (Result, error) {
	req.Action = strings.TrimSpace(req.Action)
	if req.Action == "" {
		return Result{}, errors.New("action is required")
	}
	if !validToolText(req.Action, maxActionBytes, false) {
		return Result{}, errors.New("action is invalid or exceeds the size limit")
	}
	if len(req.Inputs) > maxInputCount {
		return Result{}, errors.New("too many input fields")
	}
	for key, value := range req.Inputs {
		if strings.TrimSpace(key) == "" ||
			!validToolText(key, maxInputKeyBytes, false) {
			return Result{}, errors.New("input key is invalid")
		}
		if !validToolText(value, maxInputValueBytes, true) {
			return Result{}, errors.New("input value is invalid or exceeds the size limit")
		}
	}

	if %t && !req.Consent {
		return Result{}, errors.New("explicit consent is required before a hardware-related plan")
	}

	return Result{
		Status: "proposal_only",
		Tool: ToolName,
		Summary: "Plan created; implementation and permissions require human review.",
		CreatedAt: time.Now().UTC(),
		Evidence: []string{"evidence.json", "AWAIT_MERGE.md"},
	}, nil
}
`,
		Version,
		title,
		pkg,
		route,
		category,
		purpose,
		maxGeneratedActionBytes,
		maxGeneratedInputCount,
		maxGeneratedInputKeyLen,
		maxGeneratedInputValLen,
		goStringSlice(spec.Capabilities),
		goStringSlice(spec.Safeguards),
		spec.NeedsHardwareGuide,
	)
}

// generatedLibrary creates reusable capability contracts that describe
// interfaces but do not connect to, control, or actuate physical devices.
func generatedLibrary(spec ToolSpec) string {
	route := generatedToolRoute(spec.Name)
	pkg := generatedGoPackageName(route)

	return fmt.Sprintf(`// Generated reusable capability contracts.
// This file does not connect to or control a physical device.
package %s

type Capability struct {
	Name string
	Description string
}

var ReusableCapabilities = []Capability{
%s
}
`,
		pkg,
		goCapabilityList(spec.Capabilities),
	)
}

// goStringSlice emits bounded Go string literals. JSON quoted strings use
// escape sequences that are also valid in Go string literals.
func goStringSlice(values []string) string {
	items := generatedUniqueItems(values, maxGeneratedItems, 500)

	var b strings.Builder
	for i, value := range items {
		if i > 0 {
			b.WriteByte(',')
		}

		quoted, err := json.Marshal(value)
		if err != nil {
			b.WriteString(`""`)
			continue
		}
		b.Write(quoted)
	}

	return b.String()
}

func goCapabilityList(values []string) string {
	items := generatedUniqueItems(values, maxGeneratedItems, 500)

	var b strings.Builder
	for _, value := range items {
		quoted, err := json.Marshal(value)
		if err != nil {
			continue
		}

		fmt.Fprintf(
			&b,
			"\t{Name:%s, Description:%s},\n",
			quoted,
			quoted,
		)
	}

	return b.String()
}

// generatedTest produces a Go test suite for the generated proposal.
// The package name is normalized identically to generatedCode and
// generatedLibrary.
func generatedTest(spec ToolSpec) string {
	pkg := generatedGoPackageName(generatedToolRoute(spec.Name))

	return fmt.Sprintf(`package %s

import (
	"strings"
	"testing"
)

func TestGeneratedToolProducesProposal(t *testing.T) {
	result, err := (Tool{}).Run(Request{
		Action: "inspect",
		Consent: true,
	})
	if err != nil {
		t.Fatal(err)
	}
	if result.Status != "proposal_only" {
		t.Fatalf("expected proposal_only, got %%s", result.Status)
	}
	if result.Tool != ToolName {
		t.Fatalf("unexpected tool name: %%s", result.Tool)
	}
	if result.CreatedAt.IsZero() {
		t.Fatal("expected a creation timestamp")
	}
}

func TestGeneratedToolRejectsEmptyAction(t *testing.T) {
	if _, err := (Tool{}).Run(Request{}); err == nil {
		t.Fatal("empty action should fail")
	}
}

func TestGeneratedToolRejectsWhitespaceAction(t *testing.T) {
	if _, err := (Tool{}).Run(Request{Action: "   "}); err == nil {
		t.Fatal("whitespace-only action should fail")
	}
}

func TestGeneratedToolRejectsOversizedAction(t *testing.T) {
	action := strings.Repeat("x", maxActionBytes+1)
	if _, err := (Tool{}).Run(Request{Action: action}); err == nil {
		t.Fatal("oversized action should fail")
	}
}

func TestGeneratedToolRejectsExcessiveInputs(t *testing.T) {
	inputs := make(map[string]string, maxInputCount+1)
	for i := 0; i <= maxInputCount; i++ {
		inputs[strings.Repeat("k", 1)+string(rune('a'+i))] = "value"
	}
	if _, err := (Tool{}).Run(Request{
		Action: "inspect",
		Inputs: inputs,
		Consent: true,
	}); err == nil {
		t.Fatal("too many input fields should fail")
	}
}

func TestGeneratedToolRejectsOversizedInputValue(t *testing.T) {
	inputs := map[string]string{
		"value": strings.Repeat("x", maxInputValueBytes+1),
	}
	if _, err := (Tool{}).Run(Request{
		Action: "inspect",
		Inputs: inputs,
		Consent: true,
	}); err == nil {
		t.Fatal("oversized input value should fail")
	}
}

func TestGeneratedToolRejectsOversizedInputKey(t *testing.T) {
	inputs := map[string]string{
		strings.Repeat("k", maxInputKeyBytes+1): "value",
	}
	if _, err := (Tool{}).Run(Request{
		Action: "inspect",
		Inputs: inputs,
		Consent: true,
	}); err == nil {
		t.Fatal("oversized input key should fail")
	}
}

func TestGeneratedToolConsentPolicy(t *testing.T) {
	_, err := (Tool{}).Run(Request{Action: "inspect"})
	if %t && err == nil {
		t.Fatal("hardware-related plans should require consent")
	}
	if !%t && err != nil {
		t.Fatalf("software plan unexpectedly required consent: %%v", err)
	}
}
`,
		pkg,
		spec.NeedsHardwareGuide,
		spec.NeedsHardwareGuide,
	)
}


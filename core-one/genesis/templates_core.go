// generatedToolRoute creates a safe, predictable URL component.
func generatedToolRoute(raw string) string {
	raw = strings.ToLower(strings.TrimSpace(raw))

	var b strings.Builder
	b.Grow(minGeneratedInt(len(raw), 64))

	separator := false

	for _, r := range raw {
		switch {
		case r >= 'a' && r <= 'z',
			r >= '0' && r <= '9':
			b.WriteRune(r)
			separator = false

		case r == '-' || r == '_':
			if b.Len() > 0 && !separator {
				b.WriteRune(r)
				separator = true
			}

		default:
			if b.Len() > 0 && !separator {
				b.WriteByte('-')
				separator = true
			}
		}

		if b.Len() >= 64 {
			break
		}
	}

	result := strings.Trim(b.String(), "-_")
	if result == "" || result == "." || result == ".." {
		return "genesis-tool"
	}

	return result
}

// generatedGoPackageName converts the tool route to a valid Go package
// identifier. It deliberately avoids keywords and leading digits.
func generatedGoPackageName(route string) string {
	var b strings.Builder

	for _, r := range route {
		switch {
		case r >= 'a' && r <= 'z',
			r >= 'A' && r <= 'Z',
			r >= '0' && r <= '9':
			b.WriteRune(r)

		default:
			b.WriteByte('_')
		}
	}

	result := strings.Trim(b.String(), "_")
	if result == "" {
		result = "genesis_tool"
	}

	if result[0] >= '0' && result[0] <= '9' {
		result = "tool_" + result
	}

	if isGoKeyword(result) {
		result += "_tool"
	}

	return result
}

func isGoKeyword(value string) bool {
	switch value {
	case "break", "default", "func", "interface", "select",
		"case", "defer", "go", "map", "struct",
		"chan", "else", "goto", "package", "switch",
		"const", "fallthrough", "if", "range", "type",
		"continue", "for", "import", "return", "var":
		return true
	default:
		return false
	}
}

// generatedSingleLine prevents untrusted metadata from introducing new
// headings, source lines, or control characters into generated documents.
func generatedSingleLine(raw string, maxBytes int) string {
	if maxBytes <= 0 || !utf8.ValidString(raw) {
		return ""
	}

	var b strings.Builder
	b.Grow(minGeneratedInt(len(raw), maxBytes))

	for _, r := range raw {
		if unicode.IsControl(r) {
			r = ' '
		}

		size := utf8.RuneLen(r)
		if size <= 0 || b.Len()+size > maxBytes {
			break
		}

		b.WriteRune(r)
	}

	return strings.Join(strings.Fields(b.String()), " ")
}

func generatedUniqueItems(
	values []string,
	maxItems int,
	maxBytes int,
) []string {
	out := make([]string, 0, minGeneratedInt(len(values), maxItems))
	seen := make(map[string]struct{})

	for _, value := range values {
		value = generatedSingleLine(value, maxBytes)
		if value == "" {
			continue
		}

		key := strings.ToLower(value)
		if _, exists := seen[key]; exists {
			continue
		}

		seen[key] = struct{}{}
		out = append(out, value)

		if maxItems > 0 && len(out) >= maxItems {
			break
		}
	}

	return out
}

func minGeneratedInt(a, b int) int {
	if a < b {
		return a
	}
	return b
}

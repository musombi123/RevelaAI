func goStringSlice(values []string) string {
	var b strings.Builder
	for i, v := range values {
		if i > 0 {
			b.WriteString(",")
		}
		q, _ := json.Marshal(v)
		b.Write(q)
	}
	return b.String()
}

func goCapabilityList(values []string) string {
	var b strings.Builder
	for _, v := range values {
		q, _ := json.Marshal(v)
		fmt.Fprintf(&b, "\t{Name:%s,Description:%s},\n", q, q)
	}
	return b.String()
}

